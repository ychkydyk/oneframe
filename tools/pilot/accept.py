# -*- coding: utf-8 -*-
"""Судья приёмки: сравнивает сданный вывод с эталоном и объясняет отказ.

Опубликован ДО того, как работа сдана, и до того, как исполнитель её начал.
Судья, чей код показывают после вердикта, — не судья.

Что здесь есть и чего нет:
  есть   сравнение сданного JSON с эталоном, проверка инварианта, проверка имён
         причин, минимальный контрпример при отказе
  нет    запуска чужого кода. Мы его не запускаем — ни на своей машине, ни где
         бы то ни было: песочницы у нас нет, а без песочницы это просто
         «запустить незнакомый код у себя». Подробности в SPEC.md, раздел про
         NO_EXECUTION

Самопроверка обязательна:  python accept.py --selftest
Она кормит судью пятью заведомыми выводами: один верный и четыре испорченных
разными способами. Судья обязан принять первый и отклонить остальные, назвав
для каждого свою причину. Эталонного решения задачи здесь нет и быть не может:
самопроверка идёт по ВЫВОДАМ, а не по программам, иначе публикация судьи была бы
публикацией ответа.
"""
import json, sys

ПРИЧИНЫ = {"truncated", "not_json", "wrong_type", "missing_field", "bad_utf8"}
ПОЛЯ = ["по_типам", "испорчено", "разобрано", "не_разобрано", "всего_строк"]


def сравнить(сдано, эталон):
    """Возвращает (принято, список замечаний). Каждое замечание — контрпример."""
    зам = []

    if not isinstance(сдано, dict):
        return False, [{"поле": "-", "ожидалось": "объект JSON",
                        "получено": type(сдано).__name__}]

    for поле in ПОЛЯ:
        if поле not in сдано:
            зам.append({"поле": поле, "ожидалось": "поле присутствует", "получено": "отсутствует"})
    if зам:
        return False, зам

    чужие = set(сдано["испорчено"]) - ПРИЧИНЫ
    if чужие:
        зам.append({"поле": "испорчено", "ожидалось": "имена причин из списка",
                    "получено": sorted(чужие)})

    р, н, в = сдано["разобрано"], сдано["не_разобрано"], сдано["всего_строк"]
    if not (isinstance(р, int) and isinstance(н, int) and isinstance(в, int)):
        зам.append({"поле": "счётчики", "ожидалось": "целые числа",
                    "получено": [type(x).__name__ for x in (р, н, в)]})
    elif р + н != в:
        зам.append({"поле": "инвариант", "ожидалось": "разобрано + не_разобрано == всего_строк",
                    "получено": "%s + %s != %s" % (р, н, в)})

    for поле in ("по_типам", "испорчено"):
        ож, пол = эталон[поле], сдано[поле]
        if not isinstance(пол, dict):
            зам.append({"поле": поле, "ожидалось": "объект", "получено": type(пол).__name__})
            continue
        for ключ in sorted(set(ож) | set(пол)):
            a, b = ож.get(ключ, 0), пол.get(ключ, 0)
            if a != b:
                зам.append({"поле": "%s[%s]" % (поле, ключ), "ожидалось": a, "получено": b})

    for поле in ("разобрано", "не_разобрано", "всего_строк"):
        if сдано[поле] != эталон[поле]:
            зам.append({"поле": поле, "ожидалось": эталон[поле], "получено": сдано[поле]})

    return (not зам), зам


def вердикт(сдано, эталон, метка=""):
    принято, зам = сравнить(сдано, эталон)
    print("\n=== вердикт%s ===" % ((": " + метка) if метка else ""))
    print("  ", "ПРИНЯТО" if принято else "НЕ ПРИНЯТО")
    for з in зам[:8]:
        print("   контрпример: поле %s | ожидалось %s | получено %s" % (
            з["поле"], з["ожидалось"], з["получено"]))
    if len(зам) > 8:
        print("   ещё замечаний:", len(зам) - 8)
    return принято


def selftest():
    эталон = {"по_типам": {"view": 10, "click": 5}, "испорчено": {"truncated": 3, "not_json": 2},
              "разобрано": 15, "не_разобрано": 5, "всего_строк": 20}

    верный = json.loads(json.dumps(эталон))

    счёт_не_тот = json.loads(json.dumps(эталон))
    счёт_не_тот["по_типам"]["click"] = 4

    инвариант_сломан = json.loads(json.dumps(эталон))
    инвариант_сломан["не_разобрано"] = 4

    причина_чужая = json.loads(json.dumps(эталон))
    причина_чужая["испорчено"] = {"truncated": 3, "мусор": 2}

    поля_нет = json.loads(json.dumps(эталон))
    del поля_нет["всего_строк"]

    случаи = [("верный вывод", верный, True),
              ("счётчик на единицу меньше", счёт_не_тот, False),
              ("инвариант нарушен", инвариант_сломан, False),
              ("причина не из списка", причина_чужая, False),
              ("поля нет вовсе", поля_нет, False)]

    print("ПРОВЕРКА СУДЬИ")
    всё = True
    for имя, вывод, ждём in случаи:
        принято = вердикт(вывод, эталон, имя)
        сошлось = (принято == ждём)
        всё = всё and сошлось
        print("   ожидали %s -> %s" % ("принять" if ждём else "отклонить",
                                       "верно" if сошлось else "СУДЬЯ ОШИБСЯ"))
    print("\nВЫВОД:", "судье можно верить" if всё else "СУДЬЯ НЕГОДЕН, вердиктов не публиковать")
    return 0 if всё else 1


def main():
    арг = sys.argv[1:]
    if not арг or арг[0] in ("-h", "--help"):
        print(__doc__)
        return 0
    if арг[0] == "--selftest":
        return selftest()
    if len(арг) < 2:
        print("нужно: python accept.py <сданный.json> <эталон.json>")
        return 2
    сдано = json.load(open(арг[0], encoding="utf-8"))
    эталон = json.load(open(арг[1], encoding="utf-8"))
    принято = вердикт(сдано, эталон, арг[0])
    return 0 if принято else 1


if __name__ == "__main__":
    sys.exit(main())
