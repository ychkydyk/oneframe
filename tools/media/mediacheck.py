# -*- coding: utf-8 -*-
"""Заявлено против измеренного: что на самом деле лежит в вашем файле.

Зачем. Генераторы и апскейлеры пишут в свойствах файла одно, а внутри бывает другое:
"4K", собранный растягиванием 1080p; "60 кадров в секунду", где половина кадров
продублирована; звук 48 кГц, у которого выше 15 кГц пусто. Свойства файла этого
не показывают: там стоит то, что записал кодировщик, а не то, что есть в картинке.

Скрипт меряет три вещи и сравнивает заявленное с измеренным:

  РАЗРЕШЕНИЕ  сколько настоящей детали в кадре, а не сколько пикселей в файле
  КАДРЫ       сколько кадров различны, а не сколько их записано
  ЗВУК        докуда доходит спектр, а не какая частота стоит в заголовке

Метод один и тот же: смотрим, где сигнал упирается в шум, и сравниваем с тем,
где он упирался бы, будь заявленное правдой.

Проверка прибора обязательна:  python mediacheck.py --selftest
Скрипт сам собирает заведомо настоящий и заведомо растянутый образец и обязан их
различить. Не различает - его выводам грош цена, и он скажет об этом сам.

Нужны: numpy, opencv-python (или Pillow), ffmpeg и ffprobe в PATH.
Запуск: python mediacheck.py <файл или папка> [ещё файлы]
"""
import json, os, subprocess, sys, tempfile

import numpy as np

try:
    import cv2
    ЕСТЬ_CV = True
except Exception:
    ЕСТЬ_CV = False
    from PIL import Image

КАРТИНКИ = (".png", ".jpg", ".jpeg", ".webp", ".bmp", ".tif", ".tiff")
ВИДЕО = (".mp4", ".mov", ".mkv", ".webm", ".avi", ".m4v")
ЗВУК = (".wav", ".mp3", ".flac", ".m4a", ".aac", ".ogg")

КАДРОВ_НА_ВИДЕО = 9
ПОРОГ_ДОЛИ = 0.02          # во сколько раз мощность должна превышать опорную полосу
ВЕРСИЯ = "mediacheck/1.1"


def ffprobe(путь):
    из_ = subprocess.run(
        ["ffprobe", "-v", "error", "-print_format", "json",
         "-show_format", "-show_streams", путь],
        capture_output=True, text=True, encoding="utf-8", errors="replace")
    try:
        return json.loads(из_.stdout)
    except Exception:
        return {}


def серым(путь):
    if ЕСТЬ_CV:
        img = cv2.imdecode(np.fromfile(путь, dtype=np.uint8), cv2.IMREAD_GRAYSCALE)
        return None if img is None else img.astype(np.float64)
    im = Image.open(путь).convert("L")
    return np.asarray(im, dtype=np.float64)


def радиальный_спектр(кадр):
    """Средняя мощность по кольцам частот: доли Найквиста и мощность в них."""
    h, w = кадр.shape
    сторона = min(h, w)
    if сторона < 64:
        return None, None
    y0, x0 = (h - сторона) // 2, (w - сторона) // 2
    поле = кадр[y0:y0 + сторона, x0:x0 + сторона]
    поле = поле - поле.mean()
    окно = np.hanning(сторона)
    поле = поле * окно[:, None] * окно[None, :]
    спектр = np.abs(np.fft.fftshift(np.fft.fft2(поле))) ** 2

    ц = сторона // 2
    yy, xx = np.ogrid[:сторона, :сторона]
    r = np.sqrt((yy - ц) ** 2 + (xx - ц) ** 2)
    кольца = (r / max(ц, 1) * 64).astype(np.int32)
    кольца[кольца > 64] = 65
    сумма = np.bincount(кольца.ravel(), weights=спектр.ravel(), minlength=66)
    сколько = np.bincount(кольца.ravel(), minlength=66)
    мощн = сумма[:65] / np.maximum(сколько[:65], 1)
    доли = np.arange(65) / 64.0
    return доли, мощн


def предел_детали(кадр):
    """Докуда в кадре есть настоящая деталь, в долях от заявленного размера.

    1.0 - деталь доходит до предела, картинка своего размера.
    0.5 - выше половины пусто: детали столько, сколько в кадре вдвое меньшем.

    Считается так: берём мощность по кольцам частот, за опору принимаем низкие
    частоты самого кадра, и ищем последнее кольцо, где мощность ещё превышает
    опору в ПОРОГ_ДОЛИ раз. Опора берётся из самого кадра, а не из абсолютных
    величин: тёмный кадр и яркий кадр меряются одинаково.

    Чего эта величина НЕ различает, и это важно: растянутую картинку и просто
    мягкую или расфокусированную. У обеих верх спектра пуст по одной и той же
    причине - детали там нет. Отличить, не было её снято или её убрали при
    растяжении, по одному кадру нельзя.
    """
    доли, мощн = радиальный_спектр(кадр)
    if доли is None:
        return None
    опора = float(np.median(мощн[8:16]))
    if опора <= 0:
        return 0.0
    отн = мощн / опора
    выше = np.where(отн[5:] > ПОРОГ_ДОЛИ)[0]
    if len(выше) == 0:
        return 0.0
    return float(доли[5 + выше[-1]])


def кадры_видео(путь, сколько):
    инфо = ffprobe(путь)
    поток = next((s for s in инфо.get("streams", []) if s.get("codec_type") == "video"), {})
    длит = float(инфо.get("format", {}).get("duration") or 0) or 1.0
    кадры = []
    with tempfile.TemporaryDirectory() as врем:
        for i in range(сколько):
            t = длит * (i + 0.5) / сколько
            файл = os.path.join(врем, "k%02d.png" % i)
            subprocess.run(["ffmpeg", "-v", "error", "-ss", "%.3f" % t, "-i", путь,
                            "-frames:v", "1", "-y", файл], capture_output=True)
            if os.path.exists(файл):
                к = серым(файл)
                if к is not None:
                    кадры.append(к)
    return кадры, поток, длит


def различие_кадров(путь, предел=240):
    """Доля соседних кадров, неотличимых друг от друга."""
    with tempfile.TemporaryDirectory() as врем:
        шаблон = os.path.join(врем, "%05d.png")
        subprocess.run(["ffmpeg", "-v", "error", "-i", путь, "-vf", "scale=96:54",
                        "-frames:v", str(предел), "-y", шаблон], capture_output=True)
        файлы = sorted(os.listdir(врем))
        if len(файлы) < 3:
            return None, 0
        прошлый, одинаковых, всего = None, 0, 0
        for имя in файлы:
            к = серым(os.path.join(врем, имя))
            if к is None:
                continue
            if прошлый is not None:
                всего += 1
                if float(np.mean(np.abs(к - прошлый))) < 0.25:
                    одинаковых += 1
            прошлый = к
        return (одинаковых / всего if всего else None), всего


def полоса_звука(путь):
    """Докуда доходит спектр звука и какая частота дискретизации заявлена."""
    инфо = ffprobe(путь)
    поток = next((s for s in инфо.get("streams", []) if s.get("codec_type") == "audio"), None)
    if not поток:
        return None, None
    заявлено = int(поток.get("sample_rate") or 0)
    if not заявлено:
        return None, None
    сырое = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", путь, "-t", "20", "-ac", "1",
         "-f", "f32le", "-acodec", "pcm_f32le", "-"], capture_output=True).stdout
    x = np.frombuffer(сырое, dtype=np.float32)
    n = 1 << 15
    if x.size < n:
        return заявлено, None
    спектр = np.zeros(n // 2 + 1)
    кусков = 0
    for i in range(0, min(x.size - n, n * 40), n):
        кусок = x[i:i + n]
        if кусок.size < n:
            break
        спектр = спектр + np.abs(np.fft.rfft(кусок * np.hanning(n))) ** 2
        кусков += 1
    if кусков == 0 or спектр.sum() <= 0:
        return заявлено, None
    частоты = np.fft.rfftfreq(n, 1.0 / заявлено)
    полка = float(np.median(спектр[-(len(спектр) // 20):]))
    порог = max(полка * 8.0, float(спектр.max()) * 1e-7)
    выше = np.where(спектр > порог)[0]
    предел = float(частоты[выше[-1]]) if len(выше) else 0.0
    return заявлено, предел


def проверить_файл(путь):
    расш = os.path.splitext(путь)[1].lower()
    итог = {"файл": os.path.basename(путь), "тип": None}

    if расш in КАРТИНКИ:
        итог["тип"] = "картинка"
        к = серым(путь)
        if к is None:
            итог["ошибка"] = "не читается"
            return итог
        h, w = к.shape
        доля = предел_детали(к)
        итог["заявлено"] = "%dx%d" % (w, h)
        итог["доля_детали"] = round(доля, 3) if доля is not None else None
        if доля:
            итог["измерено"] = "%dx%d" % (int(w * доля), int(h * доля))
        return итог

    if расш in ВИДЕО:
        итог["тип"] = "видео"
        кадры, поток, длит = кадры_видео(путь, КАДРОВ_НА_ВИДЕО)
        if not кадры:
            итог["ошибка"] = "кадры не извлеклись"
            return итог
        w = int(поток.get("width") or кадры[0].shape[1])
        h = int(поток.get("height") or кадры[0].shape[0])
        доли = [предел_детали(к) for к in кадры]
        доли = [d for d in доли if d is not None]
        доля = float(np.median(доли)) if доли else None
        итог["заявлено"] = "%dx%d" % (w, h)
        итог["доля_детали"] = round(доля, 3) if доля else None
        if доля:
            итог["измерено"] = "%dx%d" % (int(w * доля), int(h * доля))
        ставка = поток.get("r_frame_rate") or "0/1"
        try:
            a, b = ставка.split("/")
            фпс = float(a) / float(b) if float(b) else 0.0
        except Exception:
            фпс = 0.0
        итог["кадров_в_сек_заявлено"] = round(фпс, 3)
        повтор, всего = различие_кадров(путь)
        итог["повторов_доля"] = round(повтор, 3) if повтор is not None else None
        итог["кадров_сравнено"] = всего
        if повтор is not None and фпс:
            итог["кадров_в_сек_различных"] = round(фпс * (1.0 - повтор), 2)
        зв, предел = полоса_звука(путь)
        if зв:
            итог["звук_заявлено_гц"] = зв
            итог["звук_предел_гц"] = int(предел) if предел else None
        return итог

    if расш in ЗВУК:
        итог["тип"] = "звук"
        зв, предел = полоса_звука(путь)
        итог["звук_заявлено_гц"] = зв
        итог["звук_предел_гц"] = int(предел) if предел else None
        return итог

    итог["тип"] = "пропущен"
    return итог


def розовый_шум(сторона, семя=3, наклон=1.1):
    """Образец со спектром, как у обычной фотографии: деталь доходит до предела.

    Синусоидальная решётка для этой роли не годится: у неё вся энергия в одной
    частоте, и после растяжения интерполятор дорисовывает звон, который прибор
    честно видит как деталь. На такой картинке прибор проваливает собственный
    контроль - проверено, первая версия проваливала.
    """
    сл = np.random.default_rng(семя)
    белый = сл.normal(0, 1, (сторона, сторона))
    F = np.fft.fftshift(np.fft.fft2(белый))
    ц = сторона // 2
    yy, xx = np.ogrid[:сторона, :сторона]
    r = np.sqrt((yy - ц) ** 2 + (xx - ц) ** 2)
    r[ц, ц] = 1.0
    поле = np.real(np.fft.ifft2(np.fft.ifftshift(F / (r ** наклон))))
    поле = (поле - поле.min()) / (поле.max() - поле.min()) * 220 + 18
    return поле


def уменьшить_вернуть(кадр, k):
    с = кадр.shape[0]
    м = max(8, int(round(с / k)))
    if ЕСТЬ_CV:
        мал = cv2.resize(кадр, (м, м), interpolation=cv2.INTER_AREA)
        return cv2.resize(мал, (с, с), interpolation=cv2.INTER_CUBIC)
    шаг = max(1, int(round(k)))
    мал = кадр[::шаг, ::шаг]
    назад = np.repeat(np.repeat(мал, шаг, axis=0), шаг, axis=1)
    return назад[:с, :с]


def selftest():
    """Прибор обязан отличить заведомо настоящее от заведомо растянутого.

    Печатается калибровочная таблица: что прибор показывает на образцах, про
    которые ответ известен заранее. Без неё число «доля детали» не с чем сверить.
    """
    print("ПРОВЕРКА ПРИБОРА,", ВЕРСИЯ)
    сторона = 512
    настоящий = розовый_шум(сторона)
    образцы = [("настоящий, без растяжения", настоящий, 1.00),
               ("растянут в 1.5 раза", уменьшить_вернуть(настоящий, 1.5), 0.67),
               ("растянут в 2 раза", уменьшить_вернуть(настоящий, 2.0), 0.50),
               ("растянут в 4 раза", уменьшить_вернуть(настоящий, 4.0), 0.25),
               ("пустой кадр", np.zeros((сторона, сторона)) + 128.0, 0.00)]
    print("  %-28s %10s %10s" % ("образец", "истина", "прибор"))
    замеры = {}
    for имя, кадр, истина in образцы:
        д = предел_детали(кадр)
        замеры[имя] = д
        print("  %-28s %10.2f %10.2f" % (имя, истина, д))

    нат = замеры["настоящий, без растяжения"]
    рас2 = замеры["растянут в 2 раза"]
    рас4 = замеры["растянут в 4 раза"]
    пуст = замеры["пустой кадр"]

    ок1 = нат > 0.85
    ок2 = рас2 < 0.70
    ок3 = (нат - рас2) > 0.25
    ок4 = рас4 < рас2
    ок5 = пуст < 0.05
    print("  настоящий читается настоящим:     ", "да" if ок1 else "НЕТ")
    print("  растянутый читается растянутым:   ", "да" if ок2 else "НЕТ")
    print("  прибор их различает:              ", "да" if ок3 else "НЕТ")
    print("  сильнее растянут - ниже показание:", "да" if ок4 else "НЕТ")
    print("  пустой кадр читается пустым:      ", "да" if ок5 else "НЕТ")
    годен = ок1 and ок2 and ок3 and ок4 and ок5
    print("  ВЫВОД:", "прибору можно верить" if годен else "ПРИБОР НЕГОДЕН, выводы не публиковать")
    print("  показания смещены вверх: растяжение в 2 раза читается не как 0.50,")
    print("  а выше - интерполятор добавляет звон. Сверяйтесь с таблицей, а не с идеалом.")
    return 0 if годен else 1


def main():
    арг = sys.argv[1:]
    if not арг or арг[0] in ("-h", "--help"):
        print(__doc__)
        return 0
    if арг[0] == "--selftest":
        return selftest()

    пути = []
    for a in арг:
        if os.path.isdir(a):
            for корень, _, файлы in os.walk(a):
                for f in файлы:
                    if os.path.splitext(f)[1].lower() in КАРТИНКИ + ВИДЕО + ЗВУК:
                        пути.append(os.path.join(корень, f))
        elif os.path.exists(a):
            пути.append(a)

    результаты = []
    for п in пути:
        try:
            р = проверить_файл(п)
        except Exception as e:
            р = {"файл": os.path.basename(п), "ошибка": type(e).__name__}
        результаты.append(р)
        print(json.dumps(р, ensure_ascii=False))
    with open("mediacheck_receipt.json", "w", encoding="utf-8") as f:
        json.dump({"версия": ВЕРСИЯ, "файлов": len(результаты), "строки": результаты},
                  f, ensure_ascii=False, indent=1)
    print("квитанция: mediacheck_receipt.json, файлов:", len(результаты))
    return 0


if __name__ == "__main__":
    sys.exit(main())
