# -*- coding: utf-8 -*-
"""Сколько детали съедает битрейт: кривая, а не мнение.

Спор, который идёт у всех: «какой битрейт ставить на экспорт». Ответы обычно
звучат как «ставь побольше» или «8 мегабит хватает всем». Здесь вместо мнения
кривая: один и тот же исходник, несколько битрейтов, измеренная доля детали.

Исходник СИНТЕТИЧЕСКИЙ и генерируется здесь же. Причины две:
  1  он воспроизводим — любой получит тот же файл той же командой;
  2  в нём нет ничьего содержимого, и спорить можно про числа, а не про вкус.

Исходник нарочно трудный: мелкий шум по всему кадру плюс движение. На гладкой
картинке (небо, однотонный фон) любой битрейт покажется достаточным, и вывод
получится ложно-обнадёживающим.

Контроль обязателен: исходник до сжатия обязан читаться как полнодетальный,
иначе мерить нечего. Если контроль не прошёл — скрипт отказывается считать.

Запуск:  python bitrate_curve.py
Нужны:   ffmpeg в PATH, numpy, opencv-python, mediacheck.py рядом
"""
import json, os, subprocess, sys, tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mediacheck import предел_детали, серым, ffprobe

БИТРЕЙТЫ = [1, 2, 4, 8, 16, 32]      # мегабит в секунду
ДЛИНА = 6                            # секунд
КАДРОВ = 5                           # сколько кадров мерить в каждом файле


def сделать_исходник(путь):
    """Трудный кадр: мелкий шум по всему полю плюс движение и контрастная сетка."""
    фильтр = (
        "nullsrc=s=1920x1080:d=%d:r=30,"
        "geq=lum='random(1)*255':cb=128:cr=128,"
        "format=gray" % ДЛИНА
    )
    subprocess.run(["ffmpeg", "-v", "error", "-f", "lavfi", "-i", фильтр,
                    "-c:v", "ffv1", "-y", путь], capture_output=True)
    return os.path.exists(путь)


def перекодировать(исходник, путь, мбит):
    subprocess.run(["ffmpeg", "-v", "error", "-i", исходник,
                    "-c:v", "libx264", "-preset", "medium",
                    "-b:v", "%dM" % мбит, "-maxrate", "%dM" % мбит,
                    "-bufsize", "%dM" % (мбит * 2), "-pix_fmt", "yuv420p",
                    "-y", путь], capture_output=True)
    return os.path.exists(путь)


def доля_детали(путь):
    инфо = ffprobe(путь)
    длит = float(инфо.get("format", {}).get("duration") or ДЛИНА)
    доли = []
    with tempfile.TemporaryDirectory() as врем:
        for i in range(КАДРОВ):
            t = длит * (i + 0.5) / КАДРОВ
            кадр = os.path.join(врем, "k%02d.png" % i)
            subprocess.run(["ffmpeg", "-v", "error", "-ss", "%.3f" % t, "-i", путь,
                            "-frames:v", "1", "-y", кадр], capture_output=True)
            if os.path.exists(кадр):
                к = серым(кадр)
                if к is not None:
                    d = предел_детали(к)
                    if d is not None:
                        доли.append(d)
    return sum(доли) / len(доли) if доли else None


def вес(путь):
    return os.path.getsize(путь) / 1024.0 / 1024.0


def main():
    рабочая = tempfile.mkdtemp(prefix="bitrate_")
    исходник = os.path.join(рабочая, "source.mkv")
    print("генерирую исходник 1920x1080, %d с, без сжатия..." % ДЛИНА)
    if not сделать_исходник(исходник):
        print("исходник не создался — нужен ffmpeg в PATH")
        return 2

    контроль = доля_детали(исходник)
    print("КОНТРОЛЬ: доля детали в несжатом исходнике %.2f" % (контроль or 0))
    if not контроль or контроль < 0.9:
        print("контроль не пройден: исходник сам по себе не полнодетальный, мерить нечего")
        return 1
    print("контроль пройден, считаю кривую\n")

    строки = []
    print("%8s %10s %12s %14s" % ("мбит/с", "вес, МБ", "доля детали", "от исходника"))
    for м in БИТРЕЙТЫ:
        путь = os.path.join(рабочая, "b%02d.mp4" % м)
        if not перекодировать(исходник, путь, м):
            continue
        d = доля_детали(путь)
        строки.append({"мбит": м, "вес_мб": round(вес(путь), 2),
                       "доля_детали": round(d, 3) if d else None,
                       "от_исходника": round(100.0 * d / контроль) if d else None})
        print("%8d %10.2f %12.2f %13d %%" % (м, вес(путь), d or 0,
                                             round(100.0 * (d or 0) / контроль)))

    json.dump({"контроль_исходника": round(контроль, 3), "длина_с": ДЛИНА,
               "разрешение": "1920x1080", "кодек": "libx264 preset medium",
               "исходник": "синтетический шум, ffv1 без потерь",
               "строки": строки},
              open("bitrate_curve.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("\nквитанция: bitrate_curve.json")
    print("рабочая папка (удалить вручную):", рабочая)
    return 0


if __name__ == "__main__":
    sys.exit(main())
