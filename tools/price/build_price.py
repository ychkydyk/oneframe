def себестоимость(модель, вход, выход, проходов):
    ци, цо = МОДЕЛИ[модель]
    сырое = (вход * ци + выход * цо) * проходов / 1_000_000.0
    return сырое * (1.0 + ПЕРЕДЕЛКИ)


def округлить(x):
    if x < 10:
        return math.ceil(x)
    if x < 100:
        return int(math.ceil(x / 5.0) * 5)
    return int(math.ceil(x / 25.0) * 25)


def округлить_вниз(x):
    """Скидочная цена округляется В ПОЛЬЗУ ЗАКАЗЧИКА, иначе округление съедает скидку:
    30 со скидкой 15 % это 25.5, а округление вверх возвращает те же 30."""
    if x < 10:
        return max(1, int(math.floor(x)))
    if x < 100:
        return int(math.floor(x / 5.0) * 5)
    return int(math.floor(x / 25.0) * 25)


def цена(модель, вход, выход, проходов, минут_человека, наценка):
    токены = себестоимость(модель, вход, выход, проходов)
    человек = минут_человека / 60.0 * ЦЕНА_ЧАСА
    основа = (токены + человек) * наценка
    базовая = max(основа, токены * МИН_ПОКРЫТИЕ + человек)
    return округлить(базовая * ПОДЪЁМ)


def предел_скидки(цена_базовая, токены, человек):
    """Максимальная скидка, при которой оба предела ещё держатся."""
