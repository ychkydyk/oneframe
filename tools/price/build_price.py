def собрать():
    строки = []
    for кат, имя, модель, вх, вых, прох, мин, нац in К:
        c = себестоимость(модель, вх, вых, прох)
        p = цена(модель, вх, вых, прох, мин, нац)
        чел_стоимость = мин / 60.0 * ЦЕНА_ЧАСА
        после_комиссии = p * (1 - КОМИССИЯ)
        покрытие = после_комиссии / c if c > 0 else 999
        предел = предел_скидки(p, c, чел_стоимость)
        по_пулам = {}
        for имя_пула, _, скидка in ПУЛЫ:
            факт = min(скидка, предел)
            цп = округлить_вниз(p * (1.0 - факт)) if факт > 0 else p
            по_пулам[имя_пула] = {"скидка": round(факт * 100), "цена": цп,
                                  "урезана": факт < скидка - 1e-9}
        строки.append({
            "пулы": по_пулам, "предел_скидки": round(предел * 100),
            "человек_долл": round(чел_стоимость, 2),
            "категория": кат, "услуга": имя, "модель": модель,
            "полоса": полоса(вх), "вход": вх, "выход": вых, "проходов": прох,
            "минут_человека": мин,
            "токены_долл": round(c, 4),
            "цена_долл": p,
            "после_комиссии": round(после_комиссии, 2),
            "покрытие": round(покрытие, 1),
            "годно": покрытие >= МИН_ПОКРЫТИЕ,
        })
    return строки


